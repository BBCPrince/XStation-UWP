static bool EmitComputeOffsetBitFieldUExtract(Xbyak::CodeGenerator& c, Xbyak::Reg32 reg,
                                              PassInfo& pass_info, IR::Inst* inst) {
    // We asume that the count is always less than 32, Is this correct?
    ASSERT(!inst->AreAllArgsImmediates());
    if (inst->Arg(0).IsImmediate()) {
        c.mov(reg, inst->Arg(0).U32());
    } else {
        ABORT_ON_FAILURE(ComputeOffset(c, reg, pass_info, inst->Arg(0)));
    }
    bool in_stack = false;
    if (inst->Arg(1).IsImmediate()) {
        c.shr(reg, inst->Arg(1).U32());
    } else {
        c.push(reg.cvt64());
        in_stack = true;
        POP_ABORT_ON_FAILURE(ComputeOffset(c, reg, pass_info, inst->Arg(1)));
        c.mov(ecx, reg);
        c.shr(dword[rsp], cl);
    }
    if (inst->Arg(2).IsImmediate()) {
        if (in_stack) {
            c.pop(reg.cvt64());
        }
        c.and_(reg, (1U << inst->Arg(2).U32()) - 1);
    } else {
        if (!in_stack) {
            c.push(reg.cvt64());
        }
        POP_ABORT_ON_FAILURE(ComputeOffset(c, reg, pass_info, inst->Arg(2)));
        c.mov(ecx, reg);
        c.mov(edx, 1);
        c.shl(edx, cl);
        c.dec(edx);
        c.and_(dword[rsp], edx);
        c.pop(reg.cvt64());
    }
    return true;
}

static bool IsAllowedOffsetInstruction(const IR::Inst* inst) {
    switch (inst->GetOpcode()) {
    case IR::Opcode::GetUserData:
    case IR::Opcode::ReadConst:
    case IR::Opcode::ReadConstBuffer:
    case IR::Opcode::IAdd32:
    case IR::Opcode::ISub32:
    case IR::Opcode::IMul32:
    case IR::Opcode::ShiftLeftLogical32:
    case IR::Opcode::ShiftRightLogical32:
    case IR::Opcode::BitwiseAnd32:
    case IR::Opcode::BitwiseOr32:
    case IR::Opcode::BitwiseXor32:
    case IR::Opcode::BitwiseNot32:
    case IR::Opcode::UMin32:
    case IR::Opcode::UMax32:
    case IR::Opcode::BitFieldUExtract:
        return true;
    default:
        return false;
    }
}

// Detroit (2026-11-08), bindless materials. A pixel shader takes its material index from an
// interpolated attribute: int(ReadFirstLane(interp(ParamN.c))) (the vertex program exports the
// same value at every vertex: float(user data + instance) + 0.5). True for such a chain, with the
// attribute. The walker gets the value from the rasterizer (Info::DrawValueFor).
static bool MatchDrawAttribute(const IR::Inst* inst, u32& param, u32& comp) {
    bool converted = false;
    for (int depth = 0; inst && depth < 8; ++depth) {
        const auto op = inst->GetOpcode();
        if (op == IR::Opcode::ConvertS32F32 || op == IR::Opcode::ConvertU32F32) {
            converted = true;
        } else if (op != IR::Opcode::ReadFirstLane && op != IR::Opcode::BitCastU32F32 &&
                   op != IR::Opcode::BitCastF32U32) {
            break;
        }
        inst = inst->Arg(0).TryInst();
    }
    if (!converted || !inst) {
        return false;
    }
    bool found = false;
    std::vector<const IR::Inst*> stack{inst};
    for (int visits = 0; !stack.empty() && visits < 64; ++visits) {
        const IR::Inst* cur = stack.back();
        stack.pop_back();
        switch (cur->GetOpcode()) {
        case IR::Opcode::GetAttribute: {
            const auto attr = cur->Arg(0).Attribute();
            if (IR::IsBarycentricCoord(attr)) {
                continue;
            }
            if (!IR::IsParam(attr) || !cur->Arg(1).IsImmediate()) {
                return false;
            }
            const u32 n = u32(attr) - u32(IR::Attribute::Param0), cc = cur->Arg(1).U32();
            if (found && (n != param || cc != comp)) {
                return false;
            }
            found = true;
            param = n;
            comp = cc;
            continue;
        }
        case IR::Opcode::FPFma32:
        case IR::Opcode::FPSub32:
        case IR::Opcode::FPAdd32:
        case IR::Opcode::FPMul32:
        case IR::Opcode::BitCastU32F32:
        case IR::Opcode::BitCastF32U32:
        case IR::Opcode::ReadFirstLane:
            for (size_t i = 0; i < cur->NumArgs(); ++i) {
                if (const IR::Inst* arg = cur->Arg(i).TryInst()) {
                    stack.push_back(arg);
                }
            }
            continue;
        default:
            return false;
        }
    }
    return found && stack.empty();
}

// The vertex side: SetAttribute ParamN.c of [FPAdd32(imm,] ConvertF32U32(GetUserData SGPRk
// [+ InstanceId])[)]: bit 31 | k << 16 | N << 8 | c, else 0.
static u32 MatchDrawValueExport(IR::Program& program) {
    for (IR::Block* block : program.blocks) {
        for (IR::Inst& inst : block->Instructions()) {
            if (inst.GetOpcode() != IR::Opcode::SetAttribute || !inst.Arg(2).IsImmediate()) {
                continue;
            }
            const auto attr = inst.Arg(0).Attribute();
            if (!IR::IsParam(attr)) {
                continue;
            }
            const IR::Inst* v = inst.Arg(1).TryInst();
            if (v && v->GetOpcode() == IR::Opcode::FPAdd32) {
                const IR::Inst* a = v->Arg(0).TryInst();
                const IR::Inst* b = v->Arg(1).TryInst();
                v = (a && v->Arg(1).IsImmediate()) ? a : (b && v->Arg(0).IsImmediate()) ? b : nullptr;
            }
            if (!v || v->GetOpcode() != IR::Opcode::ConvertF32U32) {
                continue;
            }
            const IR::Inst* x = v->Arg(0).TryInst();
            if (x && x->GetOpcode() == IR::Opcode::IAdd32) {
                const IR::Inst* a = x->Arg(0).TryInst();
                const IR::Inst* b = x->Arg(1).TryInst();
                const auto is_instance = [](const IR::Inst* i) {
                    return i && i->GetOpcode() == IR::Opcode::GetAttributeU32 &&
                           i->Arg(0).Attribute() == IR::Attribute::InstanceId;
                };
                x = is_instance(b) ? a : is_instance(a) ? b : nullptr;
            }
            if (!x || x->GetOpcode() != IR::Opcode::GetUserData) {
                continue;
            }
            const u32 k = static_cast<u32>(x->Arg(0).ScalarReg());
            const u32 n = u32(attr) - u32(IR::Attribute::Param0), cc = inst.Arg(2).U32();
            return 0x80000000u | (k << 16) | (n << 8) | cc;
        }
    }
    return 0;
}

static bool ComputeOffset(Xbyak::CodeGenerator& c, Xbyak::Reg32 reg, PassInfo& pass_info,
                          const IR::Value& off_dw) {
    ASSERT(reg != ecx && reg != edx);
    auto inst = off_dw.Inst();
    // Detroit (2026-11-08), bindless materials: the draw's material value, third argument word 0.
    if (u32 param = 0, comp = 0; inst->GetOpcode() == IR::Opcode::ReadFirstLane &&
                                 MatchDrawAttribute(inst, param, comp)) {
        c.mov(reg, dword[r11]);
        pass_info.draw_value_in = 0x80000000u | (param << 8) | comp;
        return true;
    }
    // The vertex side reads the same value directly: ReadFirstLane(user data SGPRk [+ InstanceId])
    // is user data k for the draw's first instance (Detroit's material and instance records).
    if (inst->GetOpcode() == IR::Opcode::ReadFirstLane) {
        const IR::Inst* x = inst->Arg(0).TryInst();
        if (x && x->GetOpcode() == IR::Opcode::IAdd32) {
            const IR::Inst* a = x->Arg(0).TryInst();
            const IR::Inst* b = x->Arg(1).TryInst();
            const auto is_instance = [](const IR::Inst* i) {
                return i && i->GetOpcode() == IR::Opcode::GetAttributeU32 &&
                       i->Arg(0).Attribute() == IR::Attribute::InstanceId;
            };
            x = is_instance(b) ? a : is_instance(a) ? b : nullptr;
        }
        if (x && x->GetOpcode() == IR::Opcode::GetUserData) {
            c.mov(reg, ptr[rsi + (static_cast<u32>(x->Arg(0).ScalarReg()) << 2)]);
            return true;
        }
    }
    switch (inst->GetOpcode()) {
    case IR::Opcode::GetUserData:
        c.mov(reg, ptr[rsi + (static_cast<u32>(inst->Arg(0).ScalarReg()) << 2)]);
        return true;
    case IR::Opcode::ReadConst:
    case IR::Opcode::ReadConstBuffer:
        if (u16 offset = GetFlatbufOffset(pass_info.DeduplicateInstruction(inst)); offset != 0) {
            c.mov(reg, ptr[rsi + (offset << 2)]);
            return true;
        }
        return false;
    case IR::Opcode::IAdd32:
        ABORT_ON_FAILURE(EmitComputeOffsetIAdd32(c, reg, pass_info, inst));
        return true;
    case IR::Opcode::ISub32:
        ABORT_ON_FAILURE(EmitComputeOffsetISub32(c, reg, pass_info, inst));
        return true;
    case IR::Opcode::IMul32:
        ABORT_ON_FAILURE(EmitComputeOffsetIMul32(c, reg, pass_info, inst));
        return true;
    case IR::Opcode::ShiftLeftLogical32:
        ABORT_ON_FAILURE(EmitComputeOffsetShiftLeftLogical32(c, reg, pass_info, inst));
        return true;
    case IR::Opcode::ShiftRightLogical32:
        ABORT_ON_FAILURE(EmitComputeOffsetShiftRightLogical32(c, reg, pass_info, inst));
        return true;
    case IR::Opcode::BitwiseAnd32:
        ABORT_ON_FAILURE(EmitComputeOffsetBitwiseAnd32(c, reg, pass_info, inst));
        return true;
    case IR::Opcode::BitwiseOr32:
        ABORT_ON_FAILURE(EmitComputeOffsetBitwiseOr32(c, reg, pass_info, inst));
        return true;
    case IR::Opcode::BitwiseXor32:
        ABORT_ON_FAILURE(EmitComputeOffsetBitwiseXor32(c, reg, pass_info, inst));
        return true;
    case IR::Opcode::BitwiseNot32:
        ABORT_ON_FAILURE(EmitComputeOffsetBitwiseNot32(c, reg, pass_info, inst));
        return true;
    case IR::Opcode::UMin32:
        ABORT_ON_FAILURE(EmitComputeOffsetUMin32(c, reg, pass_info, inst));
        return true;
    case IR::Opcode::UMax32:
        ABORT_ON_FAILURE(EmitComputeOffsetUMax32(c, reg, pass_info, inst));
        return true;
    case IR::Opcode::BitFieldUExtract:
        ABORT_ON_FAILURE(EmitComputeOffsetBitFieldUExtract(c, reg, pass_info, inst));
        return true;
    default: {
        // Detroit (2026-11-08): a descriptor picked by the workgroup id (the skinning shaders
        // cs 0x52263739, 0x324b5287, 0x8315ac7e, 0xb081c845: each workgroup deforms its own mesh
        // with that mesh's buffers). The walker reads the id from its third argument (r11, set
        // from rdx on entry); the rasterizer walks again per run of workgroups and dispatches
        // each run on its own (DispatchRecord). With id 0 the walk gives what it gave before.
        // BB_SRT_GROUP_SPLIT=0: off (every workgroup used workgroup 0's buffers: Chloe's face
        // missing and her body crumpled on the language menu).
        static const bool group_split = [] {
            const char* env = std::getenv("BB_SRT_GROUP_SPLIT");
            return !(env && env[0] == '0');
        }();
        if (group_split && inst->GetOpcode() == IR::Opcode::GetAttributeU32 &&
            inst->Arg(0).Attribute() == IR::Attribute::WorkgroupId && inst->Arg(1).IsImmediate() &&
            inst->Arg(1).U32() < 3) {
            const u32 comp = inst->Arg(1).U32();
            c.mov(reg, dword[r11 + comp * 4]);
            pass_info.workgroup_mask |= 1u << comp;
            static std::mutex said_lock;
            static std::set<u64> said;
            std::scoped_lock lock{said_lock};
            if (said.insert(pass_info.pgm_hash).second) {
                std::printf("SRT walker: shader %#llx: tables per workgroup (dispatches split)\n",
                            static_cast<unsigned long long>(pass_info.pgm_hash));
            }
            return true;
        }
        // God of War port (2026-11-03), dynamic descriptor indexing stage 1: an offset the shader
        // computes per wave (s_ff1 waterfall loops: FindILsb32, Phi, ReadLane, vertex data) cannot
        // be known before the draw. It counts as 0 here, so the walker copies the table's first
        // descriptor and every iteration of the shader's loop uses it: possibly the wrong texture
        // for some materials, but a valid one. Stage 2 indexes a descriptor array on the GPU.
        // Most such reads are not descriptors but constants in a loop: God of War's tile lighting
        // (cs 0xd92dd2ba, 0xe7a719c7) walks a light mask with s_ff1 and reads each light's
        // 252-byte record; with offset 0 every light was light 0 (dark 8x8-tile blocks). With
        // BB_DIRECT_MEMORY_ACCESS=1 the offset stays unknown here, the read keeps no flattened
        // slot and the shader reads guest memory itself (read_const_dynamic, through the BDA page
        // table).
        // Printed once per shader and opcode (the log drops info lines; the shader is the clue).
        const bool dynamic = EmulatorSettings.IsDirectMemoryAccessEnabled(pass_info.pgm_hash);
        static std::mutex said_lock;
        static std::set<std::pair<u64, IR::Opcode>> said;
        {
            std::scoped_lock lock{said_lock};
            if (said.emplace(pass_info.pgm_hash, inst->GetOpcode()).second) {
                std::printf("SRT walker: shader %#llx: offset from %s is per wave; %s\n",
                            static_cast<unsigned long long>(pass_info.pgm_hash),
                            std::string(magic_enum::enum_name(inst->GetOpcode())).c_str(),
                            dynamic ? "read from GPU memory" : "the first descriptor is used");
            }
        }
        if (dynamic) {
            return false;
        }
        c.xor_(reg, reg);
        return true;
    }
    }
}

static inline bool PushPtr(Xbyak::CodeGenerator& c, PassInfo& pass_info, const IR::Value& off_dw) {
    c.push(rdi);
    if (off_dw.IsImmediate()) {
        c.mov(rdi, ptr[rdi + (off_dw.U32() << 2)]);
    } else {
        ABORT_ON_FAILURE(ComputeOffset(c, r10d, pass_info, off_dw));
        c.shl(r10d, 2);
        c.mov(r10d, r10d);
        c.mov(rdi, ptr[rdi + r10]);
    }
    c.mov(r10, 0xFFFFFFFFFFFFULL);
    c.and_(rdi, r10);
    return true;
}

static inline void PopPtr(Xbyak::CodeGenerator& c) {
    c.pop(rdi);
}

// God of War port (2026-11-03), dynamic descriptor indexing stage 2 (windowed reads): a constant
// read whose offset the shader computes per wave but within known bounds (God of War's tile
// lighting walks a 32-bit light mask with s_ff1: offset = (light * 252 + 940) / 4, 235..2188) is
// served from a window of the table copied whole into the flatbuf; the shader indexes it
// (EmitReadConst). Bounds of the offset expression; `per_wave` when part of it is unknown to the
// walker (s_ff1 results and anything only bounded by a mask).
// A loop counter (Phi of an immediate start and itself plus an immediate step) is taken to run at
// most this many steps: God of War's light binning (cs 0x1c4a6ec1) loops `for (i = 0; i < count;
// i++)` over 32- and 80-byte records, count read from the table. Set per window (VisitPointer).
static thread_local u32 t_phi_cap = 0;
// God of War port (2026-11-04): the workgroup id is taken to stay below this (set per window like
// t_phi_cap). God of War's cs 0xc78d8517 (7 workgroups) reads its workgroup's 40-byte record at
// (WorkgroupId * 40 + 8) / 4: with offset 0 every workgroup read workgroup 0's and wrote through
// its buffer, which hung the Xbox GPU (0x887a0006) 4 s into the boot. A dispatch of more groups
// than the window holds reads clamped data past it (before: the first record for every group).
static thread_local u32 t_workgroup_cap = 0;
// God of War port (2026-11-04): a value the shader loads from a buffer (ReadConstBuffer) and uses
// as a record index is taken to stay below this, for the shaders BB_SRT_VALUE_SHADERS lists
// (default cs 0xc78d8517: 4 floats of record (index * 224 + 352) bytes, index from a GPU buffer;
// record 0 for every workgroup hung the Xbox GPU, and direct memory access cannot be built
// there: ErrorUnknown).
static thread_local u32 t_value_cap = 0;
// Detroit (2026-11-08): a waterfall index (ReadLane, or a Phi of it after the loop) is taken to stay
// below this, for the shaders BB_SRT_LANE_SHADERS lists (default all; 384 in chapter 1): the material and lighting pixel shaders read
// shadow records from the root table at index * 64 + 2352..2400, index * 16 + 3048, index * 4 + 3008, so
// at most 8 entries fit. Windows work on the Xbox; direct memory access cannot be built there (no
// buffer device address on Dozen: ErrorUnknown, the draws were skipped).
static thread_local u32 t_lane_cap = 0;
static bool OffsetRange(const IR::Value& value, s64& lo, s64& hi, bool& per_wave, int depth = 0) {
    if (value.IsImmediate()) {
        lo = hi = value.U32();
        return true;
    }
    IR::Inst* inst = value.TryInst();
    if (!inst || depth > 32) {
        return false;
    }
    s64 a_lo, a_hi, b_lo, b_hi;
    const auto both = [&] {
        return OffsetRange(inst->Arg(0), a_lo, a_hi, per_wave, depth + 1) &&
               OffsetRange(inst->Arg(1), b_lo, b_hi, per_wave, depth + 1);
    };
    // An operand bounded by an immediate mask or minimum: its own range, or none at all.
    const auto bounded = [&](u32 bound) {
        bool unknown_wave = false;
        if (!OffsetRange(inst->Arg(0), a_lo, a_hi, unknown_wave, depth + 1) || a_lo < 0) {
            a_lo = 0;
            a_hi = bound;
            unknown_wave = true;
        }
        per_wave |= unknown_wave;
    };
    switch (inst->GetOpcode()) {
    case IR::Opcode::FindILsb32:
        lo = 0;
        hi = 31;
        per_wave = true;
        return true;
    case IR::Opcode::GetAttributeU32:
        if (t_workgroup_cap == 0 || inst->Arg(0).Attribute() != IR::Attribute::WorkgroupId) {
            return false;
        }
        lo = 0;
        hi = s64(t_workgroup_cap) - 1;
        per_wave = true;
        return true;
    case IR::Opcode::ReadConstBuffer:
        if (t_value_cap == 0) {
            return false;
        }
        lo = 0;
        hi = s64(t_value_cap) - 1;
        per_wave = true;
        return true;
    case IR::Opcode::ReadLane:
        if (t_lane_cap == 0) {
            return false;
        }
        lo = 0;
        hi = s64(t_lane_cap) - 1;
        per_wave = true;
        return true;
    case IR::Opcode::Phi: {
        if (t_lane_cap != 0) {
            lo = 0;
            hi = s64(t_lane_cap) - 1;
            per_wave = true;
            return true;
        }
        if (t_phi_cap == 0 || inst->NumArgs() != 2) return false;
        for (size_t start = 0; start < 2; ++start) {
            const IR::Value first = inst->Arg(start);
            IR::Inst* next = inst->Arg(1 - start).TryInst();
            if (!first.IsImmediate() || !next || next->GetOpcode() != IR::Opcode::IAdd32) {
                continue;
            }
            const bool self0 = next->Arg(0).TryInst() == inst, self1 = next->Arg(1).TryInst() == inst;
            const IR::Value step = self0 ? next->Arg(1) : next->Arg(0);
            if (!(self0 || self1) || !step.IsImmediate() || s32(step.U32()) <= 0 ||
                s32(step.U32()) > 64) {
                continue;
            }
            lo = s32(first.U32());
            hi = lo + s64(t_phi_cap) * s32(step.U32());
            per_wave = true;
            return true;
        }
        return false;
    }
    case IR::Opcode::IAdd32:
        if (!both()) return false;
        lo = a_lo + b_lo;
        hi = a_hi + b_hi;
        return true;
    case IR::Opcode::ISub32:
        if (!both()) return false;
        lo = a_lo - b_hi;
        hi = a_hi - b_lo;
        return true;
    case IR::Opcode::IMul32:
        if (!both() || a_lo < 0 || b_lo < 0) return false;
        lo = a_lo * b_lo;
        hi = a_hi * b_hi;
        return true;
    case IR::Opcode::ShiftLeftLogical32:
        if (!inst->Arg(1).IsImmediate() || !OffsetRange(inst->Arg(0), a_lo, a_hi, per_wave, depth + 1) ||
            a_lo < 0 || inst->Arg(1).U32() > 16) return false;
        lo = a_lo << inst->Arg(1).U32();
        hi = a_hi << inst->Arg(1).U32();
        return true;
    case IR::Opcode::ShiftRightLogical32:
        if (!inst->Arg(1).IsImmediate() || !OffsetRange(inst->Arg(0), a_lo, a_hi, per_wave, depth + 1) ||
            a_lo < 0) return false;
        lo = a_lo >> inst->Arg(1).U32();
        hi = a_hi >> inst->Arg(1).U32();
        return true;
    case IR::Opcode::BitwiseAnd32:
        if (!inst->Arg(1).IsImmediate()) return false;
        bounded(inst->Arg(1).U32());
        lo = 0;
        hi = std::min<s64>(a_hi, inst->Arg(1).U32());
        return true;
    case IR::Opcode::UMin32:
        if (!inst->Arg(1).IsImmediate()) return false;
        bounded(inst->Arg(1).U32());
        lo = std::min<s64>(a_lo, inst->Arg(1).U32());
        hi = std::min<s64>(a_hi, inst->Arg(1).U32());
        return true;
    case IR::Opcode::BitFieldUExtract:
        if (!inst->Arg(2).IsImmediate() || inst->Arg(2).U32() > 16) return false;
        bounded((1u << inst->Arg(2).U32()) - 1);
        lo = 0;
        hi = (1 << inst->Arg(2).U32()) - 1;
        return true;
    default:
        return false;
    }
}

// The window of reads a level of the SRT keeps, and which of its reads it serves.
static constexpr u32 READCONST_WINDOW = 0x80000000u;
static constexpr s64 MAX_WINDOW_DW = 4096;
static bool Windowable(PassInfo& pass_info, const IR::Value& off_dw, IR::Inst* use, s64& lo, s64& hi,
                       u32 phi_cap, u32 workgroup_cap = 0, u32 value_cap = 0) {
    t_phi_cap = phi_cap;
    t_workgroup_cap = workgroup_cap;
    t_value_cap = value_cap;
    if (off_dw.IsImmediate() || use->GetOpcode() != IR::Opcode::ReadConst ||
        pass_info.GetUsesAsPointer(use)) {
        return false;
    }
    // Descriptors (and pointers) are assembled from several dwords: those stay as they were.
    for (const IR::Use& u : use->Uses()) {
        switch (u.user->GetOpcode()) {
        case IR::Opcode::CompositeConstructU32x2:
        case IR::Opcode::CompositeConstructU32x3:
        case IR::Opcode::CompositeConstructU32x4:
        case IR::Opcode::CompositeConstructU32x2x2:
            return false;
        default:
            break;
        }
    }
    bool per_wave = false;
    return OffsetRange(off_dw, lo, hi, per_wave) && per_wave && lo >= 0 && lo < 0x8000 &&
           hi - lo < MAX_WINDOW_DW;
}

static void VisitPointer(const IR::Value& off_dw, IR::Inst* subtree, PassInfo& pass_info,
                         Xbyak::CodeGenerator& c, bool pointer_ready = false) {
    // Detroit (2026-11-08): pointer_ready: the caller pushed rdi and loaded the pointer into it
    // (VisitBufferPointer); the rest is the same, PopPtr included.
    if (pointer_ready) {
        goto visit;
    }
    if (subtree->GetOpcode() == IR::Opcode::ReadConst && subtree->Flags<u16>() == 0 ||
        subtree->GetOpcode() == IR::Opcode::ReadConstBuffer &&
            subtree->Flags<IR::BufferInstInfo>().flatbuf_off_dw == 0) {
        return;
    }

    if (!PushPtr(c, pass_info, off_dw)) {
        if (pass_info.walk_pass == 0) {
            pass_info.deferred = true;
            return;
        }
        LOG_ERROR(Render_Recompiler, "Failed to compute offset for SRT walker");
        std::printf("SRT walker: shader %#llx: pointer offset not computed; its table is skipped\n",
                    static_cast<unsigned long long>(pass_info.pgm_hash));
        return;
    }
visit:
    PassInfo::PtrUserList* use_list = pass_info.GetUsesAsPointer(subtree);
    ASSERT(use_list);

    // First copy all the src data from this tree level
    // That way, all data that was contiguous in the guest SRT is also contiguous in the
    // flattened buffer.
    // TODO src and dst are contiguous. Optimize with wider loads/stores
    // TODO if this subtree is dynamically indexed, don't compact it (keep it sparse)
    // Windowed reads first: one window over all of this level's (God of War port, 2026-11-03).
    // The largest loop-counter bound whose window fits. Only for the shaders BB_SRT_PHI_SHADERS
    // lists (hex hashes, comma-separated; "all"): occlusion culling loops over more instances
    // than any window holds, and windowing it culled the forest (boot55phi).
    static const std::string phi_shaders = [] {
        const char* env = std::getenv("BB_SRT_PHI_SHADERS");
        return std::string(env ? env : "1c4a6ec1");
    }();
    const bool phi_allowed = phi_shaders == "all" ||
        phi_shaders.find(fmt::format("{:x}", pass_info.pgm_hash)) != std::string::npos;
    // God of War port (2026-11-04): the same caps bound the workgroup id, for every shader
    // (t_workgroup_cap). BB_SRT_WORKGROUP_WINDOWS=0: not (the first record for every workgroup).
    static const bool workgroup_windows = [] {
        const char* env = std::getenv("BB_SRT_WORKGROUP_WINDOWS");
        return !(env && env[0] == '0');
    }();
    static const std::string value_shaders = [] {
        const char* env = std::getenv("BB_SRT_VALUE_SHADERS");
        return "," + std::string(env ? env : "c78d8517") + ",";
    }();
    const bool value_allowed =
        value_shaders.find(fmt::format(",{:x},", pass_info.pgm_hash)) != std::string::npos;
    static const std::string lane_shaders = [] {
        const char* env = std::getenv("BB_SRT_LANE_SHADERS");
        return "," + std::string(env ? env : "all") + ",";
    }();
    t_lane_cap = lane_shaders == ",all," ||
                         lane_shaders.find(fmt::format(",{:x},", pass_info.pgm_hash)) !=
                             std::string::npos
                     ? 8u
                     : 0u;
    s64 window_lo = std::numeric_limits<s64>::max(), window_hi = -1;
    u32 phi_cap = 0, workgroup_cap = 0, value_cap = 0;
    for (const u32 cap : {256u, 128u, 64u, 32u, 16u, 8u, 0u}) {
        if (cap != 0 && !phi_allowed && !workgroup_windows && !value_allowed) {
            continue;
        }
        const u32 phi = phi_allowed ? cap : 0, workgroups = workgroup_windows ? cap : 0,
                  values = value_allowed ? cap : 0;
        window_lo = std::numeric_limits<s64>::max();
        window_hi = -1;
        for (auto [src_off_dw, use] : *use_list) {
            s64 lo, hi;
            if (Windowable(pass_info, src_off_dw, use, lo, hi, phi, workgroups, values)) {
                window_lo = std::min(window_lo, lo);
                window_hi = std::max(window_hi, hi);
            }
        }
        // God of War port (2026-11-04, BB_SRT_DEBUG=<hex hash>): what windowing made of each read.
        static const std::string debug_shader = [] {
            const char* env = std::getenv("BB_SRT_DEBUG");
            return std::string(env ? env : "");
        }();
        if (!debug_shader.empty() && fmt::format("{:x}", pass_info.pgm_hash) == debug_shader) {
            for (auto [src_off_dw, use] : *use_list) {
                s64 lo = 0, hi = 0;
                bool per_wave = false;
                t_phi_cap = phi;
                t_workgroup_cap = workgroups;
                t_value_cap = values;
                const bool ranged = OffsetRange(src_off_dw, lo, hi, per_wave);
                const IR::Inst* off = src_off_dw.TryInst();
                std::printf("SRT debug %#llx pass %d cap %u: read %s off %s ranged %d per_wave %d "
                            "lo %lld hi %lld pointer %d windowable %d\n",
                            (unsigned long long)pass_info.pgm_hash, pass_info.walk_pass, cap,
                            std::string(magic_enum::enum_name(use->GetOpcode())).c_str(),
                            off ? std::string(magic_enum::enum_name(off->GetOpcode())).c_str()
                                : (src_off_dw.IsImmediate() ? "imm" : "?"),
                            ranged, per_wave, (long long)lo, (long long)hi,
                            pass_info.GetUsesAsPointer(use) != nullptr,
                            Windowable(pass_info, src_off_dw, use, lo, hi, phi, workgroups, values));
            }
        }
        phi_cap = phi;
        workgroup_cap = workgroups;
        value_cap = values;
        // A shader of BB_SRT_VALUE_SHADERS goes on to smaller caps while nothing fits (at 256
        // each of cs 0xc78d8517's reads spans more than a window by itself).
        if ((window_hi < 0 && !value_allowed) ||
            (window_hi >= 0 && window_hi - window_lo < MAX_WINDOW_DW)) {
            break;
        }
    }
    std::vector<IR::Inst*> windowed;
    // BB_SRT_WINDOWS=0: no windows (the first descriptor again).
    static const bool windows_on = [] {
        const char* env = std::getenv("BB_SRT_WINDOWS");
        return !(env && env[0] == '0');
    }();
    if (windows_on && pass_info.walk_pass == 0 && window_hi >= 0 &&
        window_hi - window_lo < MAX_WINDOW_DW &&
        pass_info.dst_off_dw + (window_hi - window_lo + 1) < 0xffff) {
        const u32 base = pass_info.dst_off_dw, count = u32(window_hi - window_lo + 1);
        Xbyak::Label copy;
        c.xor_(ecx, ecx);
        c.L(copy);
        // r10d: the only load register (with rdi) SrtWalkerSignalHandler can patch.
        c.mov(r10d, dword[rdi + rcx * 4 + u32(window_lo << 2)]);
        c.mov(dword[rsi + rcx * 4 + (base << 2)], r10d);
        c.inc(ecx);
        c.cmp(ecx, count);
        c.jb(copy);
        for (auto [src_off_dw, use] : *use_list) {
            s64 lo, hi;
            if (Windowable(pass_info, src_off_dw, use, lo, hi, phi_cap, workgroup_cap, value_cap)) {
                use->SetFlags(READCONST_WINDOW | (u32(window_lo) << 16) | base);
                windowed.push_back(use);
            }
        }
        pass_info.dst_off_dw += u16(count);
        static std::mutex said_lock;
        static std::set<u64> said;
        std::scoped_lock lock{said_lock};
        if (said.insert(pass_info.pgm_hash).second) {
            std::printf("SRT walker: shader %#llx: %zu reads per wave served from a %u-dword window "
                        "(loops up to %u steps, workgroups up to %u)\n",
                        static_cast<unsigned long long>(pass_info.pgm_hash), windowed.size(), count,
                        phi_cap, workgroup_cap);
        }
    }
    for (auto [src_off_dw, use] : *use_list) {
        if (std::find(windowed.begin(), windowed.end(), use) != windowed.end()) {
            continue;
        }
        // The second walk copies only what the first could not (nothing is copied twice).
        if (pass_info.walk_pass == 1 &&
            (GetFlatbufOffset(use) != 0 ||
             (use->GetOpcode() == IR::Opcode::ReadConst && (use->Flags<u32>() & READCONST_WINDOW)))) {
            continue;
        }
        if (src_off_dw.IsImmediate()) {
            c.mov(r10d, ptr[rdi + (src_off_dw.U32() << 2)]);
        } else {
            if (!ComputeOffset(c, r10d, pass_info, src_off_dw)) {
                if (pass_info.walk_pass == 0) {
                    pass_info.deferred = true;
                    continue;
                }
                LOG_ERROR(Render_Recompiler, "Failed to compute offset for SRT walker");
                static std::mutex said_lock;
                static std::set<u64> said;
                std::scoped_lock lock{said_lock};
                if (said.insert(pass_info.pgm_hash).second) {
                    std::printf("SRT walker: shader %#llx: descriptor offset not computed in the "
                                "second walk; skipped\n",
                                static_cast<unsigned long long>(pass_info.pgm_hash));
                }
                continue;
            }
            c.shl(r10d, 2);
            c.mov(r10d, r10d);
            c.mov(r10d, dword[rdi + r10]);
        }
        c.mov(ptr[rsi + (pass_info.dst_off_dw << 2)], r10d);

        SetFlatbufOffset(use, pass_info.dst_off_dw);
        pass_info.dst_off_dw++;
    }

    // Then visit any children used as pointers
    for (const auto [src_off_dw, use] : *use_list) {
        if (pass_info.GetUsesAsPointer(use)) {
            VisitPointer(src_off_dw, use, pass_info, c);
        }
    }

    PopPtr(c);
}

// Detroit (2026-11-08), bindless materials: a pointer the shader loads from a buffer, at an
// offset the walker can compute (the material record: (material * 608 + 512) / 4 + 2 in
// Detroit's G-buffer pixel shaders), whose target holds the material's texture descriptors.
// lo = ReadConstBuffer(V#, off), hi = ReadConstBuffer(V#, off + 1), V# dwords 0 and 1 in user
// data. The walker loads the 64-bit pointer from the buffer and copies what the shader reads
// through it like any table level (VisitPointer). Anything else is left as it was.
static void VisitBufferPointer(IR::Inst* lo, IR::Inst* hi, PassInfo& pass_info,
                               Xbyak::CodeGenerator& c) {
    const auto say = [&](const char* what) {
        static std::mutex said_lock;
        static std::set<std::pair<u64, const char*>> said;
        std::scoped_lock lock{said_lock};
        if (said.emplace(pass_info.pgm_hash, what).second) {
            std::printf("SRT walker: shader %#llx: buffer pointer %s\n",
                        static_cast<unsigned long long>(pass_info.pgm_hash), what);
        }
    };
    IR::Inst* vsharp = lo->Arg(0).TryInst();
    IR::Inst* vsharp_hi = hi->Arg(0).TryInst();
    if (!vsharp || !vsharp_hi ||
        pass_info.DeduplicateInstruction(vsharp) != pass_info.DeduplicateInstruction(vsharp_hi) ||
        vsharp->GetOpcode() != IR::Opcode::CompositeConstructU32x4) {
        say("skipped: not one V#");
        return;
    }
    const IR::Inst* dw0 = vsharp->Arg(0).TryInst();
    const IR::Inst* dw1 = vsharp->Arg(1).TryInst();
    if (!dw0 || !dw1 || dw0->GetOpcode() != IR::Opcode::GetUserData ||
        dw1->GetOpcode() != IR::Opcode::GetUserData) {
        say("skipped: V# not in user data");
        return;
    }
    // hi must read the dword after lo: x and IAdd32(x, #1) (the record's first pointer: the
    // previous-frame transform, UV transforms), or IAdd32(x, #k) and IAdd32(x, #k + 1).
    const IR::Inst* off_lo = lo->Arg(1).TryInst();
    const IR::Inst* off_hi = hi->Arg(1).TryInst();
    const bool next_of_lo = off_lo && off_hi && off_hi->GetOpcode() == IR::Opcode::IAdd32 &&
                            off_hi->Arg(1).IsImmediate() && off_hi->Arg(1).U32() == 1 &&
                            off_hi->Arg(0).TryInst() == off_lo;
    const bool both_added = off_lo && off_hi && off_lo->GetOpcode() == IR::Opcode::IAdd32 &&
                            off_hi->GetOpcode() == IR::Opcode::IAdd32 &&
                            off_lo->Arg(1).IsImmediate() && off_hi->Arg(1).IsImmediate() &&
                            off_lo->Arg(0) == off_hi->Arg(0) &&
                            off_hi->Arg(1).U32() == off_lo->Arg(1).U32() + 1;
    if (!next_of_lo && !both_added) {
        say("skipped: not two consecutive dwords");
        return;
    }
    if (!pass_info.GetUsesAsPointer(lo)) {
        return;
    }
    const u32 ud0 = static_cast<u32>(dw0->Arg(0).ScalarReg());
    const u32 ud1 = static_cast<u32>(dw1->Arg(0).ScalarReg());
    c.push(rdi);
    if (!ComputeOffset(c, eax, pass_info, lo->Arg(1))) {
        c.pop(rdi);
        say("skipped: offset not computed");
        return;
    }
    // rdi = V# base address (dw0 | (dw1 & 0xffff) << 32); rdi = qword [rdi + offset * 4].
    c.mov(edi, dword[rsi + ud0 * 4]);
    c.mov(r10d, dword[rsi + ud1 * 4]);
    c.and_(r10d, 0xffff);
    c.shl(r10, 32);
    c.or_(rdi, r10);
    c.mov(r10d, eax);
    c.shl(r10, 2);
    c.mov(rdi, ptr[rdi + r10]);
    c.mov(r10, 0xFFFFFFFFFFFFULL);
    c.and_(rdi, r10);
    say("followed (bindless material)");
    VisitPointer(IR::Value{}, lo, pass_info, c, true);
}

static void GenerateSrtProgram(Info& info, PassInfo& pass_info) {
    Xbyak::CodeGenerator& c = g_srt_codegen;

    if (pass_info.srt_roots.empty() && pass_info.buffer_roots.empty()) {
        return;
    }

    // Register the signal handler for SRT walker, if not already registered
    RegisterSrtWalkerFaultHandler();
    std::scoped_lock lock{g_srt_codegen_mutex};

    info.srt_info.walker_func = c.getCurr<PFN_SrtWalker>();
    // Detroit (2026-11-08): the third argument, the workgroup id (3 dwords), stays in r11.
    c.mov(r11, rdx);
    pass_info.dst_off_dw = NUM_USER_DATA_REGS;
    ASSERT(pass_info.dst_off_dw == info.srt_info.flattened_bufsize_dw);

    for (const auto& [sgpr_base, root] : pass_info.srt_roots) {
        VisitPointer(IR::Value(static_cast<u32>(sgpr_base)), root, pass_info, c);
    }
    // Detroit (2026-11-08): BB_SRT_BUFFER_POINTERS=0: pointers loaded from buffers stay unwalked.
    static const bool buffer_pointers = [] {
        const char* env = std::getenv("BB_SRT_BUFFER_POINTERS");
        return !(env && env[0] == '0');
    }();
    if (buffer_pointers) {
        for (const auto& [lo, hi] : pass_info.buffer_roots) {
            VisitBufferPointer(lo, hi, pass_info, c);
        }
    }
    // BB_SRT_TWO_PASS=0: one walk (reads it leaves behind keep slot 0).
    static const bool two_pass = [] {
        const char* env = std::getenv("BB_SRT_TWO_PASS");
        return !(env && env[0] == '0');
    }();
    // BB_SRT_TWO_PASS_FILTER=<mask>:<value> (hex): the second walk only for shaders whose hash
    // & mask == value (bisecting a shader the second walk breaks).
    static const std::pair<u64, u64> filter = [] {
        const char* env = std::getenv("BB_SRT_TWO_PASS_FILTER");
        if (!env || !std::strchr(env, ':')) {
            return std::pair<u64, u64>{0, 0};
        }
        return std::pair<u64, u64>{std::strtoull(env, nullptr, 16),
                                   std::strtoull(std::strchr(env, ':') + 1, nullptr, 16)};
    }();
    if (two_pass && pass_info.deferred && (pass_info.pgm_hash & filter.first) == filter.second) {
        const u16 before = pass_info.dst_off_dw;
        pass_info.walk_pass = 1;
        for (const auto& [sgpr_base, root] : pass_info.srt_roots) {
            VisitPointer(IR::Value(static_cast<u32>(sgpr_base)), root, pass_info, c);
        }
        std::printf("SRT walker: shader %#llx: second walk copied %u more dwords\n",
                    static_cast<unsigned long long>(pass_info.pgm_hash),
                    unsigned(pass_info.dst_off_dw - before));
    }

    c.ret();
    c.ready();

    info.srt_info.workgroup_dependent = pass_info.workgroup_mask;
    info.srt_info.draw_value_in = pass_info.draw_value_in;
    info.srt_info.walker_func_size =
        c.getCurr() - reinterpret_cast<const u8*>(info.srt_info.walker_func);

    if (EmulatorSettings.IsDumpShaders()) {
        DumpSrtProgram(info, reinterpret_cast<const u8*>(info.srt_info.walker_func),
                       info.srt_info.walker_func_size);
    }

    info.srt_info.flattened_bufsize_dw = pass_info.dst_off_dw;
}

static bool IsReadConstSource(const IR::Value base) {
    auto* inst = base.TryInst();
    if (!inst) {
        return false;
    }
    return inst->GetOpcode() == IR::Opcode::GetUserData ||
           inst->GetOpcode() == IR::Opcode::ReadConst ||
           inst->GetOpcode() == IR::Opcode::ReadConstBuffer;
}

void SimplifyReadConstAddressAdd(IR::Inst& inst) {
    // This handles the following pattern by combining the addition with the offset
    // s_add_u32    s12, s2, <offset>
    // s_addc_u32   s13, s3, 0
    // s_load_dword s16, s[12:13], 0x0

    if (inst.GetOpcode() != IR::Opcode::ReadConst) {
        return;
    }
    IR::Inst* addr = inst.Arg(0).Inst();
    IR::Inst* hi = addr->Arg(1).TryInst();
    IR::Inst* lo = addr->Arg(0).TryInst();
    if (!hi || !lo) {
        return;
    }

    if (lo->GetOpcode() != IR::Opcode::IAdd32 || hi->GetOpcode() != IR::Opcode::IAdd32) {
        return;
    }

    IR::Value add_offset;
    IR::Value base;
    if (base = lo->Arg(0); IsReadConstSource(base)) {
        add_offset = lo->Arg(1);
    } else if (base = lo->Arg(1); IsReadConstSource(base)) {
        add_offset = lo->Arg(0);
    } else {
        return;
    }

    IR::Inst* sel = hi->Arg(1).TryInst();
    if (!sel || sel->GetOpcode() != IR::Opcode::SelectU32) {
        return;
    }

    IR::Value sel_true = sel->Arg(1);
    IR::Value sel_false = sel->Arg(2);
    if (!sel_true.IsImmediate() || !sel_false.IsImmediate() || sel_true.U32() != 1 ||
        sel_false.U32() != 0) {
        return;
    }

    addr->SetArg(0, base);
    addr->SetArg(1, hi->Arg(0));
    for (auto [user, operand] : addr->Uses()) {
        ASSERT(user->GetOpcode() == IR::Opcode::ReadConst && operand == 0);
        IR::IREmitter ir{*user->GetParent(), IR::Block::InstructionList::s_iterator_to(*user)};
        IR::U32 offset = IR::U32{user->Arg(1)};
        IR::U32 dw_add_offset =
            add_offset.IsImmediate()
                ? ir.Imm32(add_offset.U32() >> 2u)
                : IR::U32{ir.ShiftRightLogical(IR::U32{add_offset}, ir.Imm32(2u))};
        if (offset.IsImmediate() && dw_add_offset.IsImmediate()) {
            user->SetArg(1, ir.Imm32(offset.U32() + dw_add_offset.U32()));
        } else {
            user->SetArg(1, ir.IAdd(offset, dw_add_offset));
        }
    }
}

